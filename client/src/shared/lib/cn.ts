/**
 * Склеивает классы, отбрасывая `false`, `null` и `undefined` — чтобы условные классы
 * писались выражением, а не тернарником с пустой строкой.
 *
 * Конфликты классов Tailwind она не разрешает: `clsx` + `tailwind-merge` — это две
 * зависимости ради задачи, которой у нас пока нет. Вариативные классы компонент задаёт
 * таблицей, где взаимоисключающие варианты не пересекаются по свойствам.
 */
export function cn(...values: (string | false | null | undefined)[]): string {
  return values.filter(Boolean).join(' ')
}
