/**
 * Заглушка вместо запроса к ещё не существующему эндпоинту.
 *
 * Возвращает промис, а не готовое значение, специально: с ней запрос остаётся асинхронным,
 * у экрана честно возникают состояния загрузки и обновления, и подмена `mockRequest` на
 * `apiFetch` не меняет ни одного компонента — только тело функции в `api/` сущности.
 *
 * Каждое место вызова помечено TODO с ожидаемым маршрутом. Как только маршрут появится,
 * TODO снимается вместе с фикстурами; ничего, кроме этих файлов, править не придётся.
 */
export function mockRequest<T>(data: T, delayMs = 180): Promise<T> {
  return new Promise((resolve) => {
    setTimeout(() => {
      // Копия, а не сама фикстура: иначе мутация в одном экране протекла бы во все остальные,
      // и баг проявился бы только после подключения настоящего API.
      resolve(structuredClone(data))
    }, delayMs)
  })
}
